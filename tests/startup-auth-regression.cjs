'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const os=require('node:os');
const path=require('node:path');
const Module=require('node:module');
const temp=fs.mkdtempSync(path.join(os.tmpdir(),'justfun-reg-owner-regression-'));
process.env.LOCALAPPDATA=path.join(temp,'local');
process.env.PROGRAMDATA=path.join(temp,'programdata');
process.env.JF_LOG_EXE_DIR_FOR_TEST=path.join(temp,'exe');
process.env.JF_LOG_EMERGENCY_DIR_FOR_TEST=path.join(temp,'emergency');
process.env.JF_DESKTOP_UNIT_TEST='1';
const electron={app:{getPath:name=>path.join(temp,name),setPath(){}},BrowserWindow:class{},ipcMain:{handle(){},on(){}},dialog:{},shell:{},clipboard:{},session:{},Menu:{},safeStorage:{isEncryptionAvailable:()=>true,encryptString:value=>Buffer.from(value),decryptString:value=>Buffer.from(value).toString('utf8')}};
const load=Module._load;Module._load=(request,parent,isMain)=>request==='electron'?electron:load(request,parent,isMain);
const main=require('../source/application/main.js');Module._load=load;
const enc=value=>Buffer.from(JSON.stringify(value)).toString('base64url');
const token=claims=>`${enc({alg:'HS256',typ:'JWT'})}.${enc({iss:'justfun-license-api',typ:'access',exp:Math.floor(Date.now()/1000)+900,...claims})}.signature`;
const claims={sub:'usr_owner_production_123',cid:'cmp_company_production_123',did:'dev_windows_production_123',role:'owner',permissions:['*']};
const session=main.saveCloudSession({access_token:token(claims),offline_token:token({...claims,typ:'offline'}),refresh_token:'refresh',user:{full_name:'Owner',login:'admin',role:'owner',permissions:['*']},company:{code:'JFWD4H54',name:'Company'}});
assert.equal(session.company.id,claims.cid,'company id must be restored from signed cid');
assert.equal(main.companyWorkspaceId(session),claims.cid);
assert.equal(main.canConfigureCompanyServer(session),true);
const restored=main.readCloudAuthState();
assert.equal(restored.company.id,claims.cid,'stored legacy session must be migrated');
assert.equal(main.selectRegState(restored,{workspace_id:'cmp_other_company_123',address:'194.67.74.79'},'full'),null,'foreign local REG state must never be selected');
assert.equal(main.selectRegState(restored,{workspace_id:claims.cid,address:'194.67.74.79'},'full').address,'194.67.74.79');
assert.notEqual(main.regStatePath(claims.cid),main.regStatePath('cmp_other_company_123'));
fs.mkdirSync(path.dirname(main.regStatePath()),{recursive:true});
fs.writeFileSync(main.regStatePath(),JSON.stringify({workspace_id:claims.cid,address:'194.67.74.79'}),'utf8');
assert.equal(main.readLocalRegState(restored,'full').workspace_id,claims.cid);
assert.equal(fs.existsSync(main.regStatePath(claims.cid)),true,'legacy REG state must migrate into company scope');
console.log(JSON.stringify({ok:true,companyIdRecovered:true,ownerRecognized:true,foreignRegStateRejected:true,companyScopedRegState:true}));
